const { chromium } = require('@playwright/test')
const ExcelJS = require('exceljs')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://localhost:5184/tests/browser-xlsx/')
    await page.waitForFunction(() => typeof window.xlsxProof === 'function')
    const result = await page.evaluate(() => window.xlsxProof())
    assert.deepEqual(errors, [])
    assert.deepEqual(result.geometry, [640, 240])
    await page.setViewportSize({ width: 480, height: 800 })
    const resized = await page.evaluate(() => window.xlsxProof())
    assert.deepEqual(resized.geometry, result.geometry)
    assert.deepEqual(resized.model.sheets[0].columns, result.model.sheets[0].columns)
    assert.equal(result.model.sheets.length, 2)
    assert.ok(result.model.sheets[0].columns.every(column => column.width > 8 && column.width <= 60))
    assert.ok(result.model.sheets[0].rows.some(row => row.height > 20))
    const workbook = new ExcelJS.Workbook()
    await workbook.xlsx.load(Buffer.from(result.bytes))
    const sheet = workbook.getWorksheet('First')
    assert.equal(sheet.getCell('A2').value, '00123')
    assert.equal(sheet.getCell('B2').value, 42.5)
    assert.equal(sheet.getCell('B2').numFmt, '0.00')
    assert.equal(sheet.getCell('A3').value.toISOString(), '2026-11-04T00:00:00.000Z')
    assert.deepEqual(sheet.getCell('B3').value, { formula: 'B2*2', result: 85 })
    assert.deepEqual(sheet.getCell('A4').value, { text: 'Website', hyperlink: 'https://example.com/' })
    assert.equal(sheet.getCell('A2').fill.fgColor.argb, 'FF0C7828')
    assert.equal(sheet.getCell('A3').fill.fgColor.argb, 'FFDCE6F0')
    assert.equal(sheet.getCell('B1').master.address, 'A1')
    assert.equal(sheet.getImages().length, 1)
    assert.equal(workbook.getWorksheet('Second').getCell('A1').value, 'Still included')
    assert.equal(await page.locator('iframe').count(), 0)
    const output = process.env.SPOOL_PROOF_OUTPUT || path.resolve(__dirname, '../../../../../work/spool-browser-proof.xlsx')
    await fs.mkdir(path.dirname(output), { recursive: true })
    await fs.writeFile(output, Buffer.from(result.bytes))
    console.log(JSON.stringify({ sheets: workbook.worksheets.map(sheet => sheet.name), tableWidths: result.geometry, columnWidths: result.model.sheets[0].columns.map(column => column.width), rowHeights: result.model.sheets[0].rows.map(row => row.height), imageCount: sheet.getImages().length }))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
